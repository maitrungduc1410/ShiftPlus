/** Glyphs too thin to stand on: drawn, but not solid. */
export const DECOR = new Set(['`']);

/** Shifted glyphs that hurt instead of hold. */
export const HAZARDS = new Set(['*', '^']);

/** Level markers. They occupy a cell but have no terrain. */
export const GOAL = '¶';
export const SPAWN = '¤';

// US keyboard: unshifted char followed by its shifted char.
const PAIRS = '`~1!2@3#4$5%6^7&8*9(0)-_=+[{]}\\|;:\'",<.>/?';
const SHIFT_MAP = new Map<string, string>();
for (let i = 0; i < PAIRS.length; i += 2) SHIFT_MAP.set(PAIRS[i], PAIRS[i + 1]);
for (let c = 97; c <= 122; c++) SHIFT_MAP.set(String.fromCharCode(c), String.fromCharCode(c - 32));

/** What a character turns into while Shift is held. Already-shifted chars stay the same. */
export function shifted(ch: string): string {
  return SHIFT_MAP.get(ch) ?? ch;
}

export function glyph(ch: string): Glyph | undefined {
  return GLYPHS[ch];
}

export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS || ch === GOAL || ch === SPAWN;
}
